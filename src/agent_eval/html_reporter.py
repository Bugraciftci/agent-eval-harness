from __future__ import annotations

import html

from .models import SuiteReport


def render_html_report(report: SuiteReport) -> str:
    """Renders a self-contained dark-mode HTML evaluation dashboard with inline SVG charts."""
    pct = round(report.pass_rate * 100, 1)
    circumference = 2 * 3.14159 * 44
    stroke_dash = round(circumference * report.pass_rate, 2)
    max_lat = max((c.total_latency_ms for c in report.cases), default=1.0) or 1.0

    rows_html: list[str] = []
    bars_html: list[str] = []
    for idx, case in enumerate(report.cases):
        badge_cls = "pass" if case.passed else "fail"
        badge_txt = "PASS" if case.passed else "FAIL"
        metric_items = "".join(
            f"<li class=\"{'m-pass' if m.passed else 'm-fail'}\">"
            f"<strong>{html.escape(m.evaluator)}</strong> ({m.score * 100:.0f}%): {html.escape(m.detail)}</li>"
            for m in case.metrics
        )
        rows_html.append(
            f"<tr>"
            f"<td><code>{html.escape(case.case_id)}</code><details><summary>Inspect {len(case.metrics)} metrics</summary><ul>{metric_items}</ul></details></td>"
            f"<td><span class='badge {badge_cls}'>{badge_txt}</span></td>"
            f"<td>{case.weighted_score * 100:.1f}%</td>"
            f"<td>{case.total_latency_ms:.0f} ms</td>"
            f"<td>{case.total_tokens:,}</td>"
            f"<td>${case.estimated_cost_usd:.5f}</td>"
            f"</tr>"
        )
        bar_w = max(8, int((case.total_latency_ms / max_lat) * 320))
        y = 14 + idx * 28
        fill = "#22C55E" if case.passed else "#F43F5E"
        bars_html.append(
            f"<text x='0' y='{y + 12}' fill='#94A3B8' font-size='11' font-family='monospace'>{html.escape(case.case_id[:22])}</text>"
            f"<rect x='175' y='{y}' width='{bar_w}' height='16' rx='4' fill='{fill}' fill-opacity='0.85' />"
            f"<text x='{182 + bar_w}' y='{y + 12}' fill='#E2E8F0' font-size='11' font-family='monospace'>{case.total_latency_ms:.0f}ms</text>"
        )

    svg_height = max(60, 20 + len(report.cases) * 28)

    return f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width,initial-scale=1" />
<title>Agent Eval Report — {html.escape(report.suite_name)}</title>
<style>
  body {{ margin:0; font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',Roboto,sans-serif; background:#090D16; color:#E2E8F0; padding:32px; }}
  .wrap {{ max-width:1080px; margin:0 auto; }}
  h1 {{ font-size:26px; margin:0 0 8px; color:#F8FAFC; }}
  .sub {{ color:#94A3B8; margin-bottom:24px; font-size:14px; }}
  .grid {{ display:grid; grid-template-columns:repeat(auto-fit,minmax(200px,1fr)); gap:16px; margin-bottom:24px; }}
  .card {{ background:#0F172A; border:1px solid #1E293B; border-radius:14px; padding:18px; }}
  .kpi-label {{ color:#94A3B8; font-size:12px; text-transform:uppercase; letter-spacing:0.8px; }}
  .kpi-val {{ font-size:28px; font-weight:800; margin-top:6px; color:#38BDF8; }}
  .charts {{ display:grid; grid-template-columns:220px 1fr; gap:16px; margin-bottom:24px; }}
  table {{ width:100%; border-collapse:collapse; background:#0F172A; border:1px solid #1E293B; border-radius:14px; overflow:hidden; }}
  th, td {{ padding:12px 14px; text-align:left; border-bottom:1px solid #1E293B; vertical-align:top; font-size:13.5px; }}
  th {{ background:#111C33; color:#94A3B8; font-size:12px; text-transform:uppercase; }}
  .badge {{ padding:3px 9px; border-radius:999px; font-size:11px; font-weight:700; }}
  .badge.pass {{ background:rgba(34,197,94,0.16); color:#4ADE80; }}
  .badge.fail {{ background:rgba(244,63,94,0.18); color:#FB7185; }}
  details {{ margin-top:6px; color:#94A3B8; font-size:12px; }}
  summary {{ cursor:pointer; color:#38BDF8; }}
  ul {{ margin:8px 0 0; padding-left:18px; }}
  li.m-fail {{ color:#FDA4AF; }}
</style>
</head>
<body>
<div class="wrap">
  <h1>Agent Evaluation Dashboard — <code>{html.escape(report.suite_name)}</code></h1>
  <div class="sub">Generated by agent-eval-harness v2.0 • Deterministic Trajectory, SLA, Cost &amp; Safety Audit</div>
  <div class="grid">
    <div class="card"><div class="kpi-label">Pass Rate</div><div class="kpi-val">{report.passed_cases}/{report.total_cases} ({pct}%)</div></div>
    <div class="card"><div class="kpi-label">Avg Weighted Score</div><div class="kpi-val">{report.average_score * 100:.1f}%</div></div>
    <div class="card"><div class="kpi-label">P95 Latency</div><div class="kpi-val">{report.p95_latency_ms:.0f} ms</div></div>
    <div class="card"><div class="kpi-label">Total Est. Cost</div><div class="kpi-val">${report.total_cost_usd:.5f}</div></div>
  </div>
  <div class="charts">
    <div class="card" style="display:flex;align-items:center;justify-content:center;">
      <svg width="130" height="130" viewBox="0 0 120 120">
        <circle cx="60" cy="60" r="44" fill="none" stroke="#1E293B" stroke-width="12" />
        <circle cx="60" cy="60" r="44" fill="none" stroke="#22D3EE" stroke-width="12"
          stroke-dasharray="{stroke_dash} {circumference:.2f}" stroke-linecap="round" transform="rotate(-90 60 60)" />
        <text x="60" y="65" text-anchor="middle" fill="#F8FAFC" font-size="20" font-weight="800">{pct}%</text>
      </svg>
    </div>
    <div class="card">
      <div class="kpi-label" style="margin-bottom:8px;">Per-Case Latency Profile</div>
      <svg width="100%" height="{svg_height}" viewBox="0 0 560 {svg_height}">{"".join(bars_html)}</svg>
    </div>
  </div>
  <table>
    <thead><tr><th>Case</th><th>Status</th><th>Score</th><th>Latency</th><th>Tokens</th><th>Est. Cost</th></tr></thead>
    <tbody>{"".join(rows_html)}</tbody>
  </table>
</div>
</body>
</html>
"""
